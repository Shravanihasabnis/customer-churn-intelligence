"""Streamlit dashboard. Talks to the FastAPI backend (API_URL, default localhost:8000).

    streamlit run dashboard/app.py
"""
import json
import os

import httpx
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

API_URL = os.getenv("API_URL", "http://localhost:8000")

# Categorical palette, fixed order (never cycled). Risk bands use status colours + always a text label.
CAT = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
RISK_COLORS = {"Low": "#1baf7a", "Medium": "#eda100", "High": "#e34948", "Lost": "#8a8985"}
RFM_ORDER = ["Champions", "Loyal", "Potential Loyalists", "New / Recent", "At Risk", "Can't Lose Them", "Hibernating"]
RFM_COLORS = dict(zip(RFM_ORDER, CAT))
INK, MUTED = "#0b0b0b", "#52514e"

st.set_page_config(page_title="Customer Intelligence & Retention", page_icon="⚡", layout="wide")
st.markdown("""<style>
.block-container{padding-top:2rem;max-width:1250px}
div[data-testid="stMetric"]{background:#f6f6f4;border-radius:10px;padding:14px 16px}
</style>""", unsafe_allow_html=True)


# ------------------------------------------------------------------ data ----
@st.cache_data(ttl=60, show_spinner=False)
def get(path: str, **params):
    r = httpx.get(f"{API_URL}{path}", params=params or None, timeout=30)
    r.raise_for_status()
    return r.json()


def style(fig, h=340, legend=True):
    fig.update_layout(height=h, margin=dict(l=10, r=10, t=30, b=10), paper_bgcolor="rgba(0,0,0,0)",
                      plot_bgcolor="rgba(0,0,0,0)", font=dict(color=MUTED, size=12), showlegend=legend,
                      legend=dict(orientation="h", y=-0.15))
    fig.update_xaxes(showgrid=False, linecolor="#d8d7d2")
    fig.update_yaxes(gridcolor="#ecebe7", zeroline=False)
    return fig


try:
    summ = get("/summary")
except Exception as e:  # noqa: BLE001
    st.error(f"Can't reach the API at {API_URL}. Start it with `uvicorn api.main:app --port 8000`.\n\n{e}")
    st.stop()

# --------------------------------------------------------------- sidebar ----
st.sidebar.markdown("### ⚡ RetentionIQ")
page = st.sidebar.radio("Page", ["Customers & Cohorts", "Churn Risk", "Explain a Customer",
                              "Retention Actions", "Model Performance"], label_visibility="collapsed")
st.sidebar.caption(f"Scored as of **{summ['as_of']}** · churn = no order in next **{summ['churn_window_days']} days**")
st.sidebar.caption("Data is synthetic (generated by `src/data_gen.py`).")

# ------------------------------------------------- 1. Customers & Cohorts ---
if page == "Customers & Cohorts":
    st.title("Customers & Cohorts")
    st.caption("Customer segmentation, cohort analysis and retention metrics")
    seg = get("/segments")
    rfm = pd.DataFrame(seg["rfm"])
    rfm["segment"] = pd.Categorical(rfm.segment, RFM_ORDER, ordered=True)
    rfm = rfm.sort_values("segment")

    c1, c2 = st.columns([1, 1.3])
    with c1:
        st.subheader("RFM segments")
        fig = go.Figure(go.Pie(labels=rfm.segment, values=rfm.customers, hole=0.62, sort=False,
                               marker=dict(colors=[RFM_COLORS[s] for s in rfm.segment], line=dict(color="white", width=2)),
                               textinfo="percent", hovertemplate="%{label}: %{value:,} customers (%{percent})<extra></extra>"))
        st.plotly_chart(style(fig, 360), width="stretch")
    with c2:
        st.subheader("Cohort retention")
        co = pd.DataFrame(get("/cohorts", months=6, last=8)["cohorts"]).set_index("cohort")
        size = co.pop("cohort_size")
        co.columns = [f"M{c}" for c in co.columns]
        z = co.values.astype(float)
        text = [[("" if pd.isna(v) else f"{v:.0%}") for v in row] for row in z]
        fig = go.Figure(go.Heatmap(z=z, x=list(co.columns), y=[f"{i}  (n={size[i]})" for i in co.index], text=text,
                                   texttemplate="%{text}", colorscale=[[0, "#eaf2fc"], [1, "#2a78d6"]], zmin=0.3, zmax=1,
                                   showscale=False, xgap=2, ygap=2, hovertemplate="%{y} · %{x}: %{text}<extra></extra>"))
        fig.update_yaxes(autorange="reversed")
        st.plotly_chart(style(fig, 360, legend=False), width="stretch")
        st.caption("M0 = first-order month (100%). Blank cells = months that haven't happened yet.")

    st.subheader("Revenue by segment")
    tbl = rfm.rename(columns={"segment": "RFM segment", "customers": "Customers", "revenue": "Revenue",
                              "avg_clv": "Avg CLV", "avg_orders": "Avg orders", "aov": "AOV",
                              "avg_churn_prob": "Avg churn prob"})
    st.dataframe(tbl, hide_index=True, width="stretch",
                 column_config={"Avg churn prob": st.column_config.ProgressColumn(format="%.0f%%", min_value=0, max_value=1),
                                "Revenue": st.column_config.NumberColumn(format="$%.0f"),
                                "Avg CLV": st.column_config.NumberColumn(format="$%.0f"),
                                "AOV": st.column_config.NumberColumn(format="$%.0f")})

    st.subheader("Customers")
    f1, f2, _ = st.columns([1, 1, 2])
    risk = f1.selectbox("Risk band", ["All", "High", "Medium", "Low", "Lost"])
    sg = f2.selectbox("RFM segment", ["All"] + RFM_ORDER)
    res = get("/customers", limit=100, **({"risk": risk} if risk != "All" else {}), **({"segment": sg} if sg != "All" else {}))
    st.caption(f"{res['total']:,} customers match · showing top 100 by churn probability")
    st.dataframe(pd.DataFrame(res["items"]), hide_index=True, width="stretch", height=320,
                 column_config={"churn_prob": st.column_config.ProgressColumn("Churn prob", format="%.0f%%", min_value=0, max_value=1),
                                "ltv": st.column_config.NumberColumn("LTV", format="$%.0f"),
                                "expected_revenue_at_risk": st.column_config.NumberColumn("Revenue at risk", format="$%.0f")})

# ------------------------------------------------------------ 2. Churn ------
elif page == "Churn Risk":
    st.title("Churn Risk")
    st.caption("Customers who can still be saved. Those with no order in 180+ days are counted as Lost and handled as reactivation.")
    active = summ["customers"] - summ["lost"]
    m = st.columns(5)
    m[0].metric("Active customers", f"{active:,}")
    m[1].metric("High risk", f"{summ['high_risk']:,}", f"{summ['high_risk'] / max(active, 1):.0%} of active", delta_color="off")
    m[2].metric("Avg churn prob. (active)", f"{summ['avg_churn_probability_active']:.0%}")
    m[3].metric("Expected revenue at risk", f"${summ['expected_revenue_at_risk']:,.0f}")
    m[4].metric("Lost (reactivation pool)", f"{summ['lost']:,}")

    seg = pd.DataFrame(get("/segments")["rfm"])
    c1, c2 = st.columns(2)
    with c1:
        st.subheader("Risk distribution")
        order = ["Low", "Medium", "High", "Lost"]
        vals = [summ["low_risk"], summ["medium_risk"], summ["high_risk"], summ["lost"]]
        fig = go.Figure(go.Bar(x=order, y=vals, marker_color=[RISK_COLORS[o] for o in order], text=[f"{v:,}" for v in vals],
                               textposition="outside", hovertemplate="%{x}: %{y:,}<extra></extra>"))
        st.plotly_chart(style(fig, 320, legend=False), width="stretch")
    with c2:
        st.subheader("Average churn probability by RFM segment")
        s2 = seg.sort_values("avg_churn_prob")
        fig = go.Figure(go.Bar(y=s2.segment, x=s2.avg_churn_prob, orientation="h", marker_color=CAT[0],
                               text=[f"{v:.0%}" for v in s2.avg_churn_prob], textposition="outside",
                               hovertemplate="%{y}: %{x:.1%}<extra></extra>"))
        fig.update_xaxes(range=[0, 1.1], tickformat=".0%")
        st.plotly_chart(style(fig, 320, legend=False), width="stretch")

    st.subheader("Highest-value customers at risk")
    top = get("/customers", risk="High", sort="expected_revenue_at_risk", limit=25)
    st.dataframe(pd.DataFrame(top["items"]), hide_index=True, width="stretch",
                 column_config={"churn_prob": st.column_config.ProgressColumn("Churn prob", format="%.0f%%", min_value=0, max_value=1),
                                "ltv": st.column_config.NumberColumn("LTV", format="$%.0f"),
                                "expected_revenue_at_risk": st.column_config.NumberColumn("Revenue at risk", format="$%.0f")})

# --------------------------------------------------------- 3. Explain -------
elif page == "Explain a Customer":
    st.title("Explain a Customer")
    st.caption("Why does the model think this customer will churn? SHAP shows each feature's push on the prediction.")
    cand = get("/customers", risk="High", sort="expected_revenue_at_risk", limit=50)["items"]
    default = cand[0]["customer_id"] if cand else "C-10000"
    cid = st.text_input("Customer ID", default).strip()
    try:
        cust, ex = get(f"/customers/{cid}"), get(f"/customers/{cid}/explanation", top=8)
    except httpx.HTTPStatusError:
        st.warning("Customer not found. Try an ID like C-10013.")
        st.stop()

    k = st.columns(4)
    k[0].metric("Churn probability", f"{cust['churn_prob']:.0%}")
    k[1].metric("Status", cust["risk_band"])
    k[2].metric("RFM segment", cust["rfm_segment"])
    k[3].metric("Lifetime spend", f"${cust['monetary']:,.0f}")

    contrib = ex["contributions"]
    labels = ["Base rate"] + [f"{c['feature']} = {c['value']:g}" for c in contrib] + ["Other features", "Prediction"]
    fig = go.Figure(go.Waterfall(
        orientation="v", x=labels, measure=["absolute"] + ["relative"] * (len(contrib) + 1) + ["total"],
        y=[ex["base_value"]] + [c["shap"] for c in contrib] + [ex["other_features_shap"]] + [0],
        increasing=dict(marker=dict(color="#eb6834")), decreasing=dict(marker=dict(color="#2a78d6")),
        totals=dict(marker=dict(color=INK)), connector=dict(line=dict(color="#d8d7d2")),
        hovertemplate="%{x}: %{y:+.3f}<extra></extra>"))
    fig.update_xaxes(tickangle=-30)
    st.plotly_chart(style(fig, 420, legend=False), width="stretch")
    st.caption("Orange = pushes churn risk up · Blue = pushes it down. Units: probability (Random Forest) or log-odds (XGBoost).")

    st.subheader("Recommended actions")
    for a in cust["recommendations"]:
        st.markdown(f"**{a['action']}** · _{a['priority']}_ — {a['detail']}")

# ---------------------------------------------------- 4. Retention actions ---
elif page == "Retention Actions":
    st.title("Retention Actions")
    st.caption("Segment playbooks from the rule-based engine, plus a what-if scorer.")
    seg = pd.DataFrame(get("/segments")["rfm"])
    seg["segment"] = pd.Categorical(seg.segment, RFM_ORDER, ordered=True)
    seg = seg.sort_values("segment")
    fig = go.Figure(go.Treemap(labels=seg.segment, parents=[""] * len(seg), values=seg.customers,
                               marker=dict(colors=[RFM_COLORS[s] for s in seg.segment], line=dict(color="white", width=2)),
                               texttemplate="<b>%{label}</b><br>%{value:,} customers", textfont=dict(color="white", size=14)))
    st.plotly_chart(style(fig, 330, legend=False), width="stretch")

    st.subheader("Top priority list")
    pr = st.selectbox("Show", ["High", "Medium"], index=0)
    items = get("/customers", risk=pr, sort="expected_revenue_at_risk", limit=15)["items"]
    rows = []
    for it in items:
        c = get(f"/customers/{it['customer_id']}")
        rows.append({"Customer": it["customer_id"], "Segment": it["rfm_segment"], "Churn prob": it["churn_prob"],
                     "Revenue at risk": it["expected_revenue_at_risk"],
                     "Top action": c["recommendations"][0]["action"],
                     "Why": ", ".join(c["top_risk_drivers"][:3])})
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch",
                 column_config={"Churn prob": st.column_config.ProgressColumn(format="%.0f%%", min_value=0, max_value=1),
                                "Revenue at risk": st.column_config.NumberColumn(format="$%.0f")})

    st.subheader("What-if scorer")
    a, b, c = st.columns(3)
    rec = a.slider("Days since last order", 0, 400, 60)
    frq = b.slider("Orders so far", 1, 60, 8)
    mon = c.slider("Lifetime spend ($)", 20, 5000, 600)
    a, b, c = st.columns(3)
    tix = a.slider("Support tickets", 0, 8, 1)
    o90 = b.slider("Orders in last 90 days", 0, 15, 1)
    eml = c.slider("Email open rate", 0.0, 1.0, 0.3)
    body = dict(recency_days=rec, frequency=frq, monetary=mon, support_tickets=tix, orders_last_90d=o90,
                orders_last_30d=min(o90, 1), spend_last_90d=mon / max(frq, 1) * o90, email_open_rate=eml,
                avg_gap_days=max(rec / 2, 5), tenure_days=max(rec + 30, 365))
    res = httpx.post(f"{API_URL}/predict", json=body, timeout=30).json()
    st.metric("Churn probability", f"{res['churn_probability']:.0%}", res["risk_band"], delta_color="off")
    for r in res["recommendations"]:
        st.markdown(f"**{r['action']}** · _{r['priority']}_ — {r['detail']}")

# ---------------------------------------------------------- 5. Model --------
else:
    st.title("Model Performance")
    mt = get("/metrics")
    st.caption(f"Temporal holdout: trained on the snapshot 180 days before the end, tested on the snapshot 90 days before it "
               f"(later in time, no overlap in label windows). Selected model: **{mt['selected_model']}** (chosen by CV).")
    rows = [{"Model": n, "CV ROC-AUC": v["cv_roc_auc_mean"], **{k.replace('_', ' ').title(): x for k, x in v["test"].items()}}
            for n, v in mt["models"].items()]
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")
    st.info("On this synthetic data all three models score within ~0.003 AUC, and the logistic regression baseline is "
            "slightly ahead on the test snapshot: recency and activity dominate the signal. Real data with more "
            "non-linear behaviour is where the tree models should pull ahead.")

    c1, c2 = st.columns(2)
    with c1:
        st.subheader("ROC curve (test)")
        roc = mt["roc_curve"]
        fig = go.Figure()
        fig.add_scatter(x=roc["fpr"], y=roc["tpr"], mode="lines", line=dict(color=CAT[0], width=2), name=mt["selected_model"])
        fig.add_scatter(x=[0, 1], y=[0, 1], mode="lines", line=dict(color="#b8b7b0", dash="dot"), name="Random")
        fig.update_xaxes(title="False positive rate"); fig.update_yaxes(title="True positive rate")
        st.plotly_chart(style(fig, 340), width="stretch")
    with c2:
        st.subheader("Global feature importance (mean |SHAP|)")
        imp = pd.Series(mt["global_importance"]).head(10).sort_values()
        fig = go.Figure(go.Bar(y=imp.index, x=imp.values, orientation="h", marker_color=CAT[0],
                               hovertemplate="%{y}: %{x:.4f}<extra></extra>"))
        st.plotly_chart(style(fig, 340, legend=False), width="stretch")
    st.caption(f"Top-decile lift on test snapshot: {mt['top_decile_lift_test']:.2f}× the base churn rate.")
